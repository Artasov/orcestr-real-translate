type MutableRecord = Record<string, unknown>;

function setPath(target: MutableRecord, path: string, value: string): void {
  const parts = path.split(".");
  let current = target;
  for (const part of parts.slice(0, -1)) {
    const next = current[part];
    if (next && typeof next === "object" && !Array.isArray(next)) {
      current = next as MutableRecord;
    } else {
      const created: MutableRecord = {};
      current[part] = created;
      current = created;
    }
  }
  current[parts.at(-1)!] = value;
}

function buildAuthMessages(localeIndex: number): AuthMessages {
  const messages: MutableRecord = {};
  for (const [path, ...translations] of AUTH_MESSAGE_ROWS) {
    setPath(messages, path, translations[localeIndex]!);
  }
  return messages as AuthMessages;
}

export const additionalAuthMessages = Object.fromEntries(
  EXTRA_AUTH_LOCALES.map((locale, localeIndex) => [
    locale,
    buildAuthMessages(localeIndex),
  ]),
) as Record<ExtraAuthLocale, AuthMessages>;
